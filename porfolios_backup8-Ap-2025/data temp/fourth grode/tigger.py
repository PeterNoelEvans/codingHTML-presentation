import turtle
window=turtle.Screen()
window.setup(2000,1800,0,0)
window.bgcolor('skyblue')

tigger = turtle.Turtle()
tigger.shapesize(3)
tigger.shape('turtle')
tigger.penup()
tigger.goto(x=-400,y=-200)
tigger.pendown()
tigger.forward(900)
tigger.left(90)
tigger.forward(500)
tigger.left(90)
tigger.forward(900)
tigger.left(90)
tigger.forward(500)





turtle.exitonclick()