c = turtle.Turtle()
radius = 50

c.color('blue')
c.circle(radius + 150)
c.color('red')
c.circle(radius + 100)
c.color('pink')
c.circle(radius + 50)
c.color('black')
c.circle(radius)


c.color('black')
c.circle( - 200)
