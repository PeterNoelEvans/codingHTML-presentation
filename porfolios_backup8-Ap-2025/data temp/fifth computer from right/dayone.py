import turtle
jedi_and_pooh=turtle.Turtle()
jedi_and_pooh.speed(1)
jedi_and_pooh.color("green")

# this is a square
jedi_and_pooh.begin_fill()
jedi_and_pooh.forward(100)
jedi_and_pooh.left(90)
jedi_and_pooh.forward(100)
jedi_and_pooh.left(90)
jedi_and_pooh.forward(100)
jedi_and_pooh.left(90)
jedi_and_pooh.forward(100)
jedi_and_pooh.end_fill()
turtle.done()
