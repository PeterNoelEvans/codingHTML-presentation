import turtle
bonus=turtle.Turtle()
bonus.shape("turtle")
bonus.shapesize(2)
turtle.bgcolor('pink')
bonus.pensize(2)
screen=turtle.Screen()
screen.setup(2000,1800,0,0)


bonus.circle(200)
bonus.backward(200)

bonus.forward(400)

bonus.left(90)
bonus.forward(400)
bonus.left(90)
bonus.forward(400)
bonus.left(90)
bonus.forward(400)
bonus.left(90)


turtle.exitonclick()