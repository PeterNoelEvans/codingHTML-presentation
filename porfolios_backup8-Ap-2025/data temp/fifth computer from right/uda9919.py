import turtle
uda=turtle.Turtle()
screen=turtle.Screen()
screen.setup(2000,1800,0,0)
screen.bgcolor('skyblue')
uda.shape('turtle')
uda.pensize(2)
uda.speed(2)
step = 100

uda.goto(-400,-300)

uda.forward(step*9)
uda.left(90)
uda.forward(step*6)
uda.left(90)
uda.forward(step*9)
uda.left(90)
uda.forward(step*6)
uda.left(90)
















turtle.exitonclick()